/** The message shown, and returned by the API, for a pin outside the city. */
export const MAKATI_ERROR = "Pick a spot inside Makati.";

export type BoundingBox = {
  readonly south: number;
  readonly west: number;
  readonly north: number;
  readonly east: number;
};

// Derived from the ring rather than typed out, so it can never disagree with it.
// The database CHECK in supabase/migrations/20261003000600_makati_bounds.sql is
// this box plus a small margin; tests/fast/makati.test.ts holds the two together.
export const MAKATI_BBOX: BoundingBox = (() => {
  let south = Infinity;
  let west = Infinity;
  let north = -Infinity;
  let east = -Infinity;
  for (const [lng, lat] of MAKATI_OUTER) {
    south = Math.min(south, lat);
    north = Math.max(north, lat);
    west = Math.min(west, lng);
    east = Math.max(east, lng);
  }
  return { south, west, north, east };
})();

// Even-odd ray casting: count how many edges a ray running east from the point
// crosses. At city scale the earth is flat enough for this to be exact in practice.
function inRing(lat: number, lng: number, ring: ReadonlyArray<readonly [number, number]>) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [lngI, latI] = ring[i];
    const [lngJ, latJ] = ring[j];
    if (latI > lat !== latJ > lat && lng < ((lngJ - lngI) * (lat - latI)) / (latJ - latI) + lngI) {
      inside = !inside;
    }
  }
  return inside;
}

/** Whether a point lies inside Makati (and not in the South Cemetery hole). */
export function isInsideMakati(lat: number, lng: number): boolean {
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return false;
  // The box first: almost every wrong pin (Bataan, a mistyped coordinate) fails here.
  if (lat < MAKATI_BBOX.south || lat > MAKATI_BBOX.north) return false;
  if (lng < MAKATI_BBOX.west || lng > MAKATI_BBOX.east) return false;
  return inRing(lat, lng, MAKATI_OUTER) && !MAKATI_HOLES.some((hole) => inRing(lat, lng, hole));
}
